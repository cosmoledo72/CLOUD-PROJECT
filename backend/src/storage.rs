//! Blob storage abstraction. The local filesystem backend is used for
//! development and single-node installs; an S3 backend plugs in behind the
//! same trait (see SPEC, phase 2).

use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use bytes::Bytes;

pub trait BlobStore: Send + Sync + 'static {
    fn put(&self, key: &str, data: Bytes) -> impl std::future::Future<Output = Result<()>> + Send;
    fn get(&self, key: &str) -> impl std::future::Future<Output = Result<Bytes>> + Send;
    fn delete(&self, key: &str) -> impl std::future::Future<Output = Result<()>> + Send;
}

#[derive(Clone)]
pub struct LocalStore {
    root: PathBuf,
}

impl LocalStore {
    pub fn new(root: impl AsRef<Path>) -> Result<Self> {
        std::fs::create_dir_all(root.as_ref()).context("create storage dir")?;
        Ok(Self { root: root.as_ref().to_path_buf() })
    }

    /// Keys are generated by the server (`tenant/uuid`), never by clients,
    /// but path traversal is still rejected defensively.
    fn path_for(&self, key: &str) -> Result<PathBuf> {
        if key.contains("..") || key.starts_with('/') || key.contains('\\') {
            anyhow::bail!("invalid storage key");
        }
        Ok(self.root.join(key))
    }
}

impl BlobStore for LocalStore {
    async fn put(&self, key: &str, data: Bytes) -> Result<()> {
        let path = self.path_for(key)?;
        if let Some(parent) = path.parent() {
            tokio::fs::create_dir_all(parent).await?;
        }
        // Write to a temp file and rename for atomicity.
        let tmp = path.with_extension("part");
        tokio::fs::write(&tmp, &data).await?;
        tokio::fs::rename(&tmp, &path).await?;
        Ok(())
    }

    async fn get(&self, key: &str) -> Result<Bytes> {
        let path = self.path_for(key)?;
        Ok(Bytes::from(tokio::fs::read(&path).await.with_context(|| format!("read blob {key}"))?))
    }

    async fn delete(&self, key: &str) -> Result<()> {
        let path = self.path_for(key)?;
        match tokio::fs::remove_file(&path).await {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(e.into()),
        }
    }
}
